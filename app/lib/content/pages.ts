export function isServicePageHandle(handle: string): handle is ServicePageHandle {
  return SERVICE_PAGES.some((page) => page.handle === handle);
}

/** Запасний вміст сервісної сторінки; `null` для будь-якого іншого handle. */
export function getFallbackPage(handle: string): FallbackPage | null {
  const link = SERVICE_PAGES.find((page) => page.handle === handle);
  if (!link) return null;
  return { ...link, ...FALLBACK_PAGES[link.handle] };
}

/** Текст секцій одним рядком: для підрахунку слів і перевірок. */
export function sectionsToText(sections: ContentSection[]): string {
  return sections
    .flatMap((section) => [
      section.heading,
      ...section.blocks.flatMap((block) => (block.type === "list" ? block.items : [block.text])),
    ])
    .join(" ");
}
