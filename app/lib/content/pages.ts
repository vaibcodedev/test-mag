/**
 * Сервісні сторінки: список і запасний вміст.
 *
 * TODO(реальний магазин): створити в Shopify сторінки (Online Store → Pages) з цими handle.
 * Щойно сторінка з'являється в магазині, `/pages/:handle` показує її заголовок, текст і SEO,
 * а запасний вміст звідси більше не використовується. Після наповнення магазину
 * `FALLBACK_PAGES` можна видалити; `SERVICE_PAGES` лишається для навігації та sitemap.
 */

export type ContentBlock =
  { type: "paragraph"; text: string } | { type: "list"; ordered?: boolean; items: string[] };

export type ContentSection = {
  heading: string;
  blocks: ContentBlock[];
};

/** Текст сторінки чи статті: HTML із Shopify або структуровані секції запасного вмісту. */
export type ContentBody =
  { kind: "html"; html: string } | { kind: "sections"; sections: ContentSection[] };

export type ServicePageHandle =
  "delivery" | "installments" | "warranty" | "trade-in" | "returns" | "imei" | "contacts";

export type ServicePageLink = { handle: ServicePageHandle; title: string };

export type FallbackPage = ServicePageLink & {
  /** Один-два речення під заголовком; вони ж ідуть у meta description. */
  description: string;
  sections: ContentSection[];
};

